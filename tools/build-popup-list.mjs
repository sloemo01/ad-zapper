/*
 * Generates src/popup-hosts.js, the host blocklist the popup killer injects
 * into every page. Two sources, merged and sorted:
 *
 *   1. a curated list of popunder networks, kept here on purpose because it is
 *      small and auditable (these exist to open windows, not to serve banners);
 *   2. hosts harvested from the filter lists for rules that opt into popup
 *      filtering (`$popup`), which is how list maintainers tag them.
 *
 * The output is one newline-delimited string, not an array. This file is parsed
 * in every frame of every page, and 2.7k separate JS strings plus a Set to hold
 * them costs hundreds of KB of heap per frame; a single packed string costs the
 * list size and nothing else. Lookups pad the candidate host with newlines and
 * use a substring test, which is fast enough for the two call sites (window.open
 * and script insertions).
 *
 * Run: node tools/build-popup-list.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const CURATED = [
  // Adsterra family. The vfxmed.com loader pointed straight at these.
  'adsterra.com',
  'displayvertising.com',
  'pemsrv.com',
  // popunder and popup networks
  'popads.net',
  'popcash.net',
  'propellerads.com',
  'propellerpops.com',
  'hilltopads.net',
  'monetag.com',
  'adcash.com',
  'clickadu.com',
  'exoclick.com',
  'juicyads.com',
  'trafficstars.com',
  'trafficjunky.com',
  'mgid.com',
  'admaven.com',
  'onclickads.net',
  'onclickmax.com',
  'popmyads.com',
  'adspyglass.com',
  'adnium.com',
  // rotating hosts seen in the wild, kept until the lists catch up
  'hkryzvagqpjuj.com',
  'oqhbgxvk.com',
  'd3mzokty951c5w.cloudfront.net'
];

// `||host^$popup` is the canonical way a list says "this one opens windows".
const extractPopupHosts = (text) => {
  const hosts = new Set();
  for (const line of text.split('\n')) {
    if (!line.startsWith('||') || !line.includes('$popup')) continue;
    const match = line.match(/^\|\|([a-z0-9.-]+)\^/i);
    if (match) hosts.add(match[1].toLowerCase());
  }
  return hosts;
};

const listsDir = join(import.meta.dirname, 'lists');
let harvested = new Set();
let files = [];
try {
  files = readdirSync(listsDir).filter((name) => name.endsWith('.txt'));
} catch (err) {
  console.log('tools/lists missing, using the curated list only (run tools/fetch-lists.mjs)');
}
for (const file of files) {
  const found = extractPopupHosts(readFileSync(join(listsDir, file), 'utf8'));
  for (const host of found) harvested.add(host);
}

const harvestedCount = harvested.size;
const merged = new Set([...harvested, ...CURATED]);
const hosts = [...merged].sort();

// The killer has to answer "is this host listed" synchronously, in every frame,
// without the heap cost of a Set. So the list ships as one packed string plus a
// Bloom filter: a host that misses the filter is definitely not listed, and only
// the ~1% that hit it pay for the string search. 16 bits per host, two indices
// derived from one FNV-1a hash.
const HASH = (text) => {
  let hash = 2166136261;
  for (let index = 0; index < text.length; index++) {
    hash ^= text.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
};

const BITS_PER_HOST = 16;
const bitCount = Math.max(8, hosts.length * BITS_PER_HOST);
const bitBytes = Buffer.alloc(Math.ceil(bitCount / 8));
const setBit = (index) => {
  bitBytes[index >> 3] |= 1 << (index & 7);
};
const bitSet = (index) => (bitBytes[index >> 3] & (1 << (index & 7))) !== 0;
const indicesOf = (text) => {
  const hash = HASH(text);
  return [hash % bitCount, (hash >>> 16) % bitCount];
};
for (const host of hosts) {
  for (const index of indicesOf(host)) setBit(index);
}
// No false negatives: every listed host must pass its own filter.
for (const host of hosts) {
  for (const index of indicesOf(host)) {
    if (!bitSet(index)) throw new Error(`bloom filter lost ${host} (bit ${index})`);
  }
}
const bits = bitBytes.toString('base64');

// Chunked so the generated file stays readable: each chunk is its own literal,
// concatenated at load time into the one packed string the killer uses.
const CHUNK = 400;
const parts = [];
for (let i = 0; i < hosts.length; i += CHUNK) parts.push(hosts.slice(i, i + CHUNK));
const literals = parts.map((part, index) => {
  const text = (index === 0 ? '\n' : '') + part.join('\n') + '\n';
  return `  ${JSON.stringify(text)}`;
});

const out = `/*
 * Generated by tools/build-popup-list.mjs. Do not edit by hand.
 * ${hosts.length} hosts, ${hosts.join('\n').length} bytes of text, as of ${new Date().toISOString().slice(0, 10)}.
 *
 * One packed newline-delimited string: see the generator for why it is not an
 * array. Every line is a host, padded with a leading and trailing newline so a
 * lookup is a plain substring test.
 *
 * __yazPopupBits is a Bloom filter over the same hosts (${BITS_PER_HOST} bits each): the killer
 * checks it first, so the string search only runs on the ~1% that slip through.
 */
self.__yazPopupHosts =
${literals.join(' +\n')};
self.__yazPopupHostCount = ${hosts.length};
self.__yazPopupBits = ${JSON.stringify(bits)};
self.__yazPopupBitCount = ${bitCount};
// The same FNV-1a the generator used to set those bits, so there is exactly one
// implementation of the hash in the pipeline and the build can prove every
// listed host passes its own filter.
self.__yazPopupHash = function (text) {
  var hash = 2166136261;
  for (var index = 0; index < text.length; index++) {
    hash ^= text.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
};
`;

const target = join(import.meta.dirname, '..', 'src', 'popup-hosts.js');
writeFileSync(target, out);
const packedLength = 1 + hosts.join('\n').length + 1;
console.log(
  `src/popup-hosts.js: ${hosts.length} hosts packed into ${packedLength} bytes (${harvestedCount} harvested from $popup rules, ${CURATED.length} curated)`
);
